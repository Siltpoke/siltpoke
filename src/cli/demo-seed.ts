// ── Optionally clear demo data ─────────────────────────────────────────────

/** Prefix patterns that identify demo/smoke seeded spans */
const DEMO_PREFIXES = ["c-demo-", "c-smoke-"];

function isDemoId(id: string | null | undefined): boolean {
  if (!id) return false;
  return DEMO_PREFIXES.some((p) => id.startsWith(p));
}

export async function clearDemoData(): Promise<void> {
  // 1. Remove c-demo-* critique markdown files
  const dayDir = join(getHome(), "critiques", "archive", today);
  if (existsSync(dayDir)) {
    const files = await readdir(dayDir);
    for (const f of files) {
      if (f.startsWith("c-demo-")) {
        await rm(join(dayDir, f));
      }
    }
  }

  // 2. Wipe demo spans from SQLite index
  const tracesDir = join(getHome(), "traces");
  const dbPath = join(tracesDir, "index.sqlite");
  if (existsSync(dbPath)) {
    const db = new Database(dbPath);
    const _result = db.exec(
      `DELETE FROM spans WHERE critique_id LIKE 'c-demo-%' OR critique_id LIKE 'c-smoke-%'`
    );
    db.close();
  }

  // 3. Filter demo span lines from JSONL files
  if (existsSync(tracesDir)) {
    const jsonlFiles = (await readdir(tracesDir)).filter((f) => f.endsWith(".jsonl"));
    for (const f of jsonlFiles) {
      const filePath = join(tracesDir, f);
      const raw = await readFile(filePath, "utf8");
      const lines = raw.split("\n").filter((l) => l.trim() !== "");
      const kept = lines.filter((l) => {
        try {
          const span = JSON.parse(l) as { attributes?: Record<string, unknown> };
          const cid = span.attributes?.["siltpoke.critique_id"] as string | undefined;
          return !isDemoId(cid);
        } catch {
          return true; // keep malformed lines rather than lose data
        }
      });
      if (kept.length !== lines.length) {
        const _removed = lines.length - kept.length;
        await writeFile(filePath, kept.length > 0 ? `${kept.join("\n")}\n` : "");
      }
    }
  }
}

// ── Main ───────────────────────────────────────────────────────────────────

export async function main(): Promise<void> {

  if (flagClear) {
    await clearDemoData();
  }
  for (const c of CRITIQUES) await writeCritique(c);
  for (const c of CRITIQUES) await writeTraceFor(c.id);
  await writeBiasAuditSamples();

  if (!flagSkipBuild) {
    const cwd = process.cwd();
    const _idx = await buildRepoMemoryIndex({
      cwd,
      pattern: "src/critic/**/*.ts",
    });
    const _fs = await buildFewShotIndex({});
  } else {
  }
}

// Run when invoked directly (not imported in tests)
if (import.meta.main) {
  main().catch((e: unknown) => {
    console.error("\nSeed failed:", e);
    process.exit(1);
  });
}
