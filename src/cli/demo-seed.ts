async function writeCritique(c: CritiqueSpec): Promise<void> {
  const dir = join(getHome(), "critiques", "archive", today);
  await mkdir(dir, { recursive: true });
  const evidenceYaml = c.evidence
    .map(
      (e) =>
        `  - rule_id: ${e.rule_id}\n    tier: ${e.tier}\n    file: ${e.file}\n    line: ${e.line}\n    snippet: "${e.snippet.replace(/"/g, '\\"')}"\n    signal_source: ${e.signal_source}`,
    )
    .join("\n");

  // Captured user query for Block A demo.
  const capturedIntentLines = c.user_raw_query
    ? `user_raw_query: ${JSON.stringify(c.user_raw_query)}`
    : "user_raw_query: null";

  const md = `---
schemaVersion: 2
critique_id: ${c.id}
ts: ${new Date().toISOString()}
intent_classification: ${c.intent}
intent_confidence: ${c.intent_conf}
category: ${c.category}
severity: ${c.severity}
confidence: ${c.confidence}
status: pending
signal_sources: [${c.evidence.map((e) => e.signal_source).join(", ")}]
reasoning: ${JSON.stringify(c.reasoning)}
critique_for_claude: ${JSON.stringify(c.critique_for_claude)}
suggested_fix: ${JSON.stringify(c.suggested_fix)}
mood: concerned
pose: base
bubble_short: ${JSON.stringify(c.bubble_short)}
bubble_long: ""
xp_earned_events: []
evidence:
${evidenceYaml}
${capturedIntentLines}
---
Demo seed critique — ${c.id}. Generated by \`bun src/cli/demo-seed.ts\`.
`;
  await writeFile(join(dir, `${c.id}.md`), md);
}

